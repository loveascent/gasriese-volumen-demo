// Block AgX: Blender-4.0-Farbabbildung (Konstanten wie three.js AgXToneMapping) + sRGB-Ausgabekurve.
export const WGSL_AGX = /* wgsl */`
const SRGB_TO_REC2020 = mat3x3<f32>(0.6274039, 0.0690973, 0.0163914, 0.3292830, 0.9195404, 0.0880133, 0.0433131, 0.0113623, 0.8955953);
const REC2020_TO_SRGB = mat3x3<f32>(1.6604910, -0.1245505, -0.0181508, -0.5876411, 1.1328999, -0.1005789, -0.0728499, -0.0083494, 1.1187297);
const AGX_INSET = mat3x3<f32>(0.856627153315983, 0.137318972929847, 0.11189821299995, 0.0951212405381588, 0.761241990602591, 0.0767994186031903, 0.0482516061458583, 0.101439036467562, 0.811302368396859);
const AGX_OUTSET = mat3x3<f32>(1.1271005818144368, -0.1413297634984383, -0.14132976349843826, -0.11060664309660323, 1.157823702216272, -0.11060664309660294, -0.016493938717834573, -0.016493938717834257, 1.2519364065950405);
fn agxContrast(x: vec3<f32>) -> vec3<f32> {
  let x2 = x * x; let x4 = x2 * x2;
  return 15.5 * x4 * x2 - 40.14 * x4 * x + 31.96 * x4 - 6.868 * x2 * x + 0.4298 * x2 + 0.1191 * x - 0.00232;
}
fn agx(c0: vec3<f32>) -> vec3<f32> {
  var c = SRGB_TO_REC2020 * c0;
  c = AGX_INSET * c;
  c = max(c, vec3<f32>(1e-10));
  c = log2(c);
  c = clamp((c - (-12.47393)) / (4.026069 - (-12.47393)), vec3<f32>(0.0), vec3<f32>(1.0));
  c = agxContrast(c);
  c = AGX_OUTSET * c;
  c = pow(max(c, vec3<f32>(0.0)), vec3<f32>(2.2));
  return clamp(REC2020_TO_SRGB * c, vec3<f32>(0.0), vec3<f32>(1.0));
}
fn oetf(c: vec3<f32>) -> vec3<f32> {
  return select(1.055 * pow(c, vec3<f32>(1.0 / 2.4)) - 0.055, 12.92 * c, c <= vec3<f32>(0.0031308));
}
`;
